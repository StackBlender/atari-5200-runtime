def glyph(drawing):
    if not isinstance(drawing, str):
        raise ValueError('drawing must be a string')
    rows = drawing.split('/')
    if not 1 <= len(rows) <= 8 or any(len(row) != 5 or set(row)-{'.', '#'} for row in rows):
        raise ValueError('drawing must have one to eight five-pixel rows')
    data = bytearray(8)
    for y, row in enumerate(rows):
        for x, pixel in enumerate(row, 1):
            if pixel == '#':
                data[y] |= 1 << (7-x)
    return bytes(data)


def asset():
    if set(DRAWINGS) != {chr(code) for code in range(32,127)}:
        raise ValueError('exact printable ASCII repertoire required')
    data = b''.join(glyph(DRAWINGS[chr(code)]) for code in range(32,127))
    report = dict(schema=1, purpose='standalone-original-printable-glyphs-only',
                  runtime_abi=None, atari_encoding=None, bank_address=None,
                  provider_approved=False, execution_verified=False,
                  capabilities=[], glyph_count=95, bytes_per_glyph=8,
                  ascii_first=32, ascii_last=126, size=len(data),
                  sha256=hashlib.sha256(data).hexdigest(),
                  source_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest())
    return data, json.dumps(report,sort_keys=True,indent=2)+'\n'


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir',required=True,type=Path)
    args=parser.parse_args()
    try:
        data,report=asset()
    except ValueError as error:
        parser.error(str(error))
    args.output_dir.mkdir(parents=True,exist_ok=True)
    (args.output_dir/'printable-glyphs.bin').write_bytes(data)
    (args.output_dir/'printable-glyphs.json').write_text(report)


if __name__=='__main__':
    main()
